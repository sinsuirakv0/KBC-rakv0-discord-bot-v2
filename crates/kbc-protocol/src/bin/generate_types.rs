use std::error::Error;
use std::fs;
use std::path::PathBuf;

use kbc_protocol::{CoreAction, CoreEvent, PROTOCOL_VERSION, RuntimeInfo};
use ts_rs::{Config, TS};

fn main() -> Result<(), Box<dyn Error>> {
    let workspace_dir = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../..");
    let output_dir = workspace_dir.join("apps/discord/src/protocol/generated");
    let config = Config::new().with_out_dir(&output_dir);

    fs::create_dir_all(&output_dir)?;
    CoreEvent::export_all(&config)?;
    CoreAction::export_all(&config)?;
    RuntimeInfo::export_all(&config)?;

    let version_source = format!(
        "// This file is generated by kbc-protocol. Do not edit it manually.\nexport const PROTOCOL_VERSION = {PROTOCOL_VERSION} as const;\n"
    );
    fs::write(output_dir.join("version.ts"), version_source)?;

    Ok(())
}
